// 用最小輸入組出合法 MarketBrief（citationUrls 對齊唯一 citation、其餘欄位填空陣列）。
function makeBrief(input: BriefInput): MarketBrief {
  return {
    headline: input.headline,
    summary: input.headline,
    citations: [{ title: '來源', url: CITE, quote: '佐證' }],
    narrative: {
      intro: input.intro,
      sections: input.sections.map(s => ({ heading: s.heading, body: s.body, takeaway: null, relatedNewsIds: [], claimIds: [], citationUrls: [CITE] })),
      outro: input.outro,
    },
    cascadeChains: [],
    relatedNews: [],
    affectedIndustries: [],
    relatedETFs: [],
    reasoningChain: ['能源通膨傳導', '半導體出口管制'],
    disclaimer: '本分析僅供參考、非投資建議、實際投資請諮詢專業人士',
  }
}

